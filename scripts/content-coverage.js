#!/usr/bin/env node
'use strict';
// Measures how much content each game really has per language by executing data/<lang>/*.js
// (they populate window.gameData[lang][gameKey]) and counting leaf items.
//   node scripts/content-coverage.js           print the table
//   node scripts/content-coverage.js --write   also write docs/CONTENT_COVERAGE.md
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const LANGS = ['en', 'fr', 'es', 'de', 'it', 'ru', 'el', 'pt', 'hy', 'ka', 'ba', 'tt', 'br', 'cv'];
// gameData key -> game id (word-linker and story-chain also draw on COSYdata vocabulary at runtime)
const KEY_TO_GAME = {
  action: 'action-hero', battle: 'battle-of-wits', critic: 'critics-corner', etymology: 'etymology-explorer',
  fluency: 'fluency-flow', identity: 'identity-mystery', opinions: 'opinion-arena', storychain: 'story-chain', wordlinker: 'word-linker',
};

function load() {
  const sb = { console: { log() {}, warn() {}, error() {} } };
  sb.window = sb; sb.self = sb;
  vm.createContext(sb);
  for (const l of LANGS) {
    const dir = path.join(root, 'data', l);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.js'))) {
      vm.runInContext(fs.readFileSync(path.join(dir, f), 'utf8'), sb, { filename: `${l}/${f}` });
    }
  }
  return sb.gameData || {};
}
const count = (v) => (Array.isArray(v) ? v.length : v && typeof v === 'object' ? Object.values(v).reduce((n, x) => n + count(x), 0) : v ? 1 : 0);

function table() {
  const gd = load();
  const menus = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(root, 'games', 'index.json'), 'utf8')).map((g) => [g.id, g.learning_languages]));
  const rows = [];
  for (const [key, game] of Object.entries(KEY_TO_GAME)) {
    rows.push({
      game, key, menu: menus[game] || [],
      counts: Object.fromEntries(LANGS.map((l) => [l, gd[l] && gd[l][key] !== undefined ? count(gd[l][key]) : null])),
    });
  }
  return rows;
}

function markdown(rows) {
  const head = `| Game | ${LANGS.join(' | ')} |\n|---|${LANGS.map(() => '--:').join('|')}|\n`;
  const body = rows.map((r) => `| ${r.game} | ${LANGS.map((l) => {
    const n = r.counts[l];
    const cell = n === null ? '–' : String(n);
    return r.menu.includes(l) ? `**${cell}**` : cell;
  }).join(' | ')} |`).join('\n');
  return `# Content coverage per game and language

Generated by \`node scripts/content-coverage.js --write\`; do not edit by hand. Numbers are leaf items (prompts, entries, identities...)
found in \`data/<lang>/*.js\`. **Bold** = the language is offered in the game's practice-language menu (\`games/index.json\`). \`–\` = no entry for that key.
Games not listed (Hot Seat, Last Letter, Object Quest, Scene Match, Cosy Crossword, Lucky Numbers, Story Weaver, Emoji Odyssey, This or That,
100 Questions) take their content from COSYdata or from their own folders, so they have no \`data/<lang>\` counts.
Word Linker and Story Chain fall back to COSYdata vocabulary when a language has no static items.

${head}${body}

## Reading the table
- Bold cells with small numbers are the weakest offers; a plain cell with a large number is content that exists but is not offered.
- A candidate rule for offering a language: at least 75% of the median item count of the languages already offered.
`;
}

const rows = table();
const md = markdown(rows);
if (process.argv.includes('--write')) {
  fs.writeFileSync(path.join(root, 'docs', 'CONTENT_COVERAGE.md'), md);
  console.log('Wrote docs/CONTENT_COVERAGE.md');
} else {
  console.log(md);
}
