#!/usr/bin/env node
/**
 * scripts/vendor-fonts.js
 *
 * Vendors the three families COSYgames uses (Fraunces, DM Sans, Nunito) so the
 * app makes no third-party font request. `shared/css/tokens.css` used to
 * `@import` the Google Fonts CSS; this replaces that with a self-hosted
 * `shared/css/fonts.css` plus the woff2 files in `shared/fonts/`.
 *
 * Run once, or when the font list changes:
 *   node scripts/vendor-fonts.js
 *
 * The script is deterministic: re-running it produces byte-identical files.
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const ROOT = path.resolve(__dirname, '..');
const FONT_DIR = path.join(ROOT, 'shared', 'fonts');
const FONTS_CSS = path.join(ROOT, 'shared', 'css', 'fonts.css');
const TOKENS_CSS = path.join(ROOT, 'shared', 'css', 'tokens.css');

// A modern desktop UA makes Google serve woff2 rather than ttf.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  { css: 'Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,600;1,9..144,300', slug: 'fraunces' },
  { css: 'DM+Sans:wght@400;500;700', slug: 'dm-sans' },
  { css: 'Nunito:ital,wght@0,400;0,600;0,700;0,800;0,900;1,700', slug: 'nunito' },
];

function get(url, binary) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': UA } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return get(res.headers.location, binary).then(resolve, reject);
      }
      if (res.statusCode !== 200) return reject(new Error(`${res.statusCode} for ${url}`));
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(binary ? Buffer.concat(chunks) : Buffer.concat(chunks).toString('utf8')));
    }).on('error', reject);
  });
}

async function main() {
  fs.mkdirSync(FONT_DIR, { recursive: true });

  const blocks = [];
  const seen = new Map();

  for (const fam of FAMILIES) {
    const css = await get(`https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`, false);
    const faceRe = /@font-face\s*\{([\s\S]*?)\}/g;
    let m;
    while ((m = faceRe.exec(css))) {
      const body = m[1];
      const url = /url\((https:[^)]+\.woff2)\)/.exec(body);
      if (!url) continue;
      const weight = /font-weight:\s*([^;]+);/.exec(body);
      const style = /font-style:\s*([^;]+);/.exec(body);
      const range = /unicode-range:\s*([^;]+);/.exec(body);
      const subset = /\/\*\s*([a-z-]+)\s*\*\//.exec(css.slice(Math.max(0, m.index - 40), m.index));
      const name = `${fam.slug}-${(subset ? subset[1] : 'latin')}-${(style ? style[1] : 'normal')}-${(weight ? weight[1].replace(/[^0-9]/g, '') : '400')}.woff2`;

      if (!seen.has(url[1])) {
        const buf = await get(url[1], true);
        fs.writeFileSync(path.join(FONT_DIR, name), buf);
        seen.set(url[1], name);
      }

      blocks.push(
        '@font-face {\n' +
        `  font-family: '${/font-family:\s*'?([^';]+)'?;/.exec(body)[1]}';\n` +
        `  font-style: ${style ? style[1] : 'normal'};\n` +
        `  font-weight: ${weight ? weight[1] : '400'};\n` +
        '  font-display: swap;\n' +
        `  src: url(../fonts/${seen.get(url[1])}) format('woff2');\n` +
        (range ? `  unicode-range: ${range[1]};\n` : '') +
        '}'
      );
    }
  }

  const header =
    '/* Self-hosted fonts (no third-party requests). Generated by scripts/vendor-fonts.js.\n' +
    '   Fraunces, DM Sans and Nunito, SIL Open Font License 1.1. */\n\n';
  fs.writeFileSync(FONTS_CSS, header + blocks.join('\n\n') + '\n');

  // Point tokens.css at the local file instead of Google.
  const tokens = fs.readFileSync(TOKENS_CSS, 'utf8');
  const updated = tokens.replace(
    /@import url\('https:\/\/fonts\.googleapis\.com[^']*'\);/,
    "@import url('fonts.css');"
  );
  if (updated === tokens && !tokens.includes("url('fonts.css')")) {
    throw new Error('Could not find the Google Fonts @import in tokens.css');
  }
  fs.writeFileSync(TOKENS_CSS, updated);

  console.log(`Vendored ${seen.size} woff2 files into shared/fonts/ and wrote shared/css/fonts.css.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
